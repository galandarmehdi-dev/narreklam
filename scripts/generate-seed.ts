/**
 * Generates supabase/seed.sql from the bundled catalog (src/content/catalog) and FAQ defaults.
 * Run: npm run seed:generate   → then apply seed.sql once in the Supabase SQL editor (or `supabase db reset`).
 * The seed is idempotent: it skips the catalog if categories already exist.
 */
import { writeFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { defaultCategories, defaultServices } from '../src/content/catalog';
import { defaultFaq } from '../src/content/demo';
import { EDITABLE_KEYS } from '../src/i18n/editable';
import { LOCALES } from '../src/lib/types';

const q = (s: string | null | undefined) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(',')}]::text[]` : `'{}'::text[]`);
const jsonb = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const out: string[] = [];
out.push('-- AUTO-GENERATED by scripts/generate-seed.ts — do not edit by hand.');
out.push('-- Default NarReklam catalog (6 categories, 18 services, all sub-services) in az/ru/en.\n');
out.push(`insert into public.site_settings (id) values (1) on conflict (id) do nothing;\n`);
out.push(`insert into public.content_blocks (key, grp) values\n${EDITABLE_KEYS.map((k) => `  (${q(k.key)}, ${q(k.group)})`).join(',\n')}\non conflict (key) do nothing;\n`);

out.push('do $seed$\nbegin');
out.push(`  if exists (select 1 from public.service_categories) then\n    raise notice 'Catalog already present — skipping catalog seed';\n  else`);

const catIds = new Map<string, string>();
for (const c of defaultCategories) {
  const id = randomUUID();
  catIds.set(c.id, id);
  out.push(`    insert into public.service_categories (id, slug, sort_order, icon, art) values (${q(id)}, ${q(c.slug)}, ${c.order}, ${q(c.icon)}, ${q(c.art)});`);
  for (const l of LOCALES) {
    out.push(`    insert into public.service_category_translations (category_id, locale, name, tagline, description) values (${q(id)}, '${l}', ${q(c.name[l])}, ${q(c.tagline[l])}, ${q(c.description[l])});`);
  }
}
for (const s of defaultServices) {
  const id = randomUUID();
  out.push(`    insert into public.services (id, slug, category_id, sort_order, icon, quote_fields) values (${q(id)}, ${q(s.slug)}, ${q(catIds.get(s.categoryId)!)}, ${s.order}, ${q(s.icon)}, ${arr(s.quoteFields)});`);
  for (const l of LOCALES) {
    out.push(
      `    insert into public.service_translations (service_id, locale, title, short, headline, intro, applications, faq, keywords) values (${q(id)}, '${l}', ${q(s.title[l])}, ${q(s.short[l])}, ${q(s.headline[l])}, ${q(s.intro[l])}, ${arr(s.applications[l])}, ${jsonb(s.faq[l])}, ${q(s.keywords[l])});`,
    );
  }
  s.items.forEach((it, i) => {
    const iid = randomUUID();
    out.push(`    insert into public.service_items (id, service_id, sort_order) values (${q(iid)}, ${q(id)}, ${i});`);
    out.push(`    insert into public.service_item_translations (item_id, locale, name) values ${LOCALES.map((l) => `(${q(iid)}, '${l}', ${q(it.name[l])})`).join(', ')};`);
  });
}
out.push('  end if;\n');
out.push(`  if not exists (select 1 from public.faq_items) then`);
for (const f of defaultFaq) {
  const id = randomUUID();
  out.push(`    insert into public.faq_items (id, sort_order) values (${q(id)}, ${f.order});`);
  out.push(`    insert into public.faq_translations (faq_id, locale, question, answer) values ${LOCALES.map((l) => `(${q(id)}, '${l}', ${q(f.question[l])}, ${q(f.answer[l])})`).join(', ')};`);
}
out.push('  end if;\nend\n$seed$;\n');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`seed.sql written: ${defaultCategories.length} categories, ${defaultServices.length} services, ${defaultServices.reduce((n, s) => n + s.items.length, 0)} sub-services, ${defaultFaq.length} FAQ.`);
